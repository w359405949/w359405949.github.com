function battleMessageStateParameters(selected, snapshot, phase, index) {
  const catalog = state.project.ui.construction.templates_data.battle_message_runtime_parameters;
  const enemyCall = snapshot.domainResults.enemyCall || snapshot.context.enemyCall;
  const attack = snapshot.domainResults.itemAttack;
  const attackMessage = snapshot.execution.messageContexts?.[index];
  const enemySlot = attackMessage?.target ?? enemyCall?.messageTargets?.[index] ?? enemyCall?.actor;
  const enemy = attackMessage ? attack?.instances?.[enemySlot]
    : selectedPath(selected).enemyActionReference ? enemyCall?.instances?.[enemySlot] : null;
  const partyTarget = enemyCall?.messagePartyTargets?.[index];
  const identity = {battle_id: 'message-preview', action_id: selected.path,
    target_iteration: attackMessage?.iteration ?? index, target_slot: attackMessage?.target ?? -1,
    result_execution: selectedPath(selected).resultScript};
  const actor = enemy && !attackMessage ? {kind: 'enemy', slot: enemyCall.actor}
    : snapshot.context.messageActor || (snapshot.context.actor.startsWith('save-vehicle:')
    ? {kind: 'vehicle', id: Number(snapshot.context.actor.split(':')[1])}
    : {kind: 'role', id: snapshot.context.role});
  const target = attackMessage?.party ? actor : Number.isInteger(partyTarget) ? {kind: 'role', id: partyTarget}
    : enemy ? {kind: 'enemy', slot: enemySlot} : undefined;
  const battle = {origin: catalog.current_value_contract.battle_origin, identity, actor,
    target, enemy_instances: attack?.instances || enemyCall?.instances, enemy_groups: attack?.groups || enemyCall?.groups,
    item: snapshot.context.item, save_slot: snapshot.context.slot, state: phase.state.split(':')[0],
    text_record_ref: phase.text_record_ref};
  const quantity = Number.isInteger(attackMessage?.quantity) ? attackMessage.quantity
    : Number.isInteger(partyTarget) && index === 1 ? enemyCall?.messageQuantity : undefined;
  if (Number.isInteger(quantity)) {
    const pending = [phase.text_record_ref.node_id], visited = new Set(), quantities = [];
    while (pending.length) {
      const node = pending.pop();
      if (visited.has(node)) continue;
      visited.add(node);
      const record = catalog.records[node];
      quantities.push(...(record?.insertions || []).filter(row =>
        row.source === 'ui-text-provider-zero-page-overlays.battle-quantity').map(row => ({
        text_record_ref: {resource_id: 'text-record', node_id: node}, command_index: row.command_index})));
      pending.push(...(record?.fixed_includes || []).map(row => row.text_record_ref.node_id));
    }
    if (quantities.length === 1) battle.quantity = {...quantities[0],
      origin: catalog.current_value_contract.quantity_origin, identity,
      phase: catalog.current_value_contract.quantity_phase, value: quantity};
  }
  const values = createBattleContextValues({catalog, readBattle: () => battle,
    readSaveFields: () => snapshotFields(selected, snapshot), readItem: id => selected.items.find(row => row.id === id),
    readMonster: id => selected.monsters?.find(row => row.id === id)});
  const parameter = (writer, subject, subject_binding) => ({writer, subject, subject_binding,
    phase: catalog.current_value_contract.parameter_phase, identity});
  const enemyParameter = enemy && {...parameter('enemy-context', Number.isInteger(partyTarget) ? 'actor' : 'target',
    {kind: 'enemy', slot: enemySlot,
    group: enemy.group, monster_id: enemy.monster_id}),
    population_snapshot: enemy.population_snapshot, suffix_source: enemy.suffix_source};
  const parameters = enemy ? {
    ...(Number.isInteger(partyTarget) ? {
      'ui-text-provider-workspace.current-string': parameter('save-name', 'target', target),
    } : {}),
    ...(battle.quantity ? {
      'ui-text-provider-zero-page-overlays.battle-quantity': parameter('quantity-result', 'quantity', target),
    } : {}),
    'ui-text-provider-zero-page-overlays.current-record': enemyParameter,
    'ui-text-provider-workspace.target-instance-suffix': enemyParameter,
    ...(attackMessage ? {'ui-text-provider-workspace.current-string': parameter('save-name', 'actor', actor)} : {}),
  } : {
    'ui-text-provider-workspace.current-string': parameter('save-name', 'actor', actor),
    'ui-text-provider-zero-page-overlays.current-record': parameter('item-reference', 'item', battle.item),
  };
  if (attackMessage?.party) parameters['ui-text-provider-workspace.current-string'] = parameter('save-name', 'target', target);
  if (attackMessage && battle.quantity) parameters['ui-text-provider-zero-page-overlays.battle-quantity'] =
    parameter('quantity-result', 'quantity', attackMessage.party ? target :
      {kind: 'enemy', slot: enemySlot, group: enemy.group, monster_id: enemy.monster_id});
  const invocation = values.forMessage({...battle, parameters});
  return {invocation, resolveRuntimeParameter: values.resolveRuntimeParameter};
}

