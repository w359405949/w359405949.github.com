export function dialogueRuntimeParameters(values) {
  const read = name => fieldSubmenuCodeValue(values, `dialogue-${name}`);
  const source = (read('scroll-origin-low') | read('scroll-origin-high') << 8);
  if (source < 0x6000 || source >= 0x6400 || !read('scroll-width') || !read('scroll-rows'))
    throw new TypeError('对话滚屏参数超出逻辑画面缓冲区');
  return {line_step: read('line-step'), visible_lines: read('visible-lines'),
    text_origin: read('text-origin'), line_origin: read('line-origin'),
    prefix_retreat: read('prefix-retreat'), prefix_region: read('prefix-region'),
    cursor_retreat: read('cursor-retreat'), line_count_register: 0x059D,
    scroll: {source_origin: source - 0x6000, width: read('scroll-width'), rows: read('scroll-rows'),
      row_retreat: read('scroll-row-retreat'), source_step: read('scroll-source-step'),
      target_step: read('scroll-target-step'), passes: 2},
    wait: {column_bias: read('wait-column-bias'), tile: read('wait-tile'),
      frame_mask: read('wait-frame-mask'), hidden_tile: read('wait-hidden-tile'),
      input_mask: read('wait-input-mask'), clear_tile: read('wait-clear-tile'),
      cursor_retreat: read('wait-cursor-retreat'), row_shift: read('wait-row-shift')}};
}

export function dialogueChoiceParameters(values) {
  const read = name => fieldSubmenuCodeValue(values, `confirm-${name}`);
  return {region: read('text-region'), record: read('text-record'), sprite: read('cursor-sprite'),
    x_bias: read('cursor-x-bias'), y_bias: read('cursor-y-bias'), x_spacing: read('choice-x-spacing')};
}

const parametersByName = new Map(FIELD_SUBMENU_CODE_PARAMETERS.map(row => [row.name, row]));

export function fieldSubmenuCodeSource(name) {
  const source = parametersByName.get(name);
  if (!source) throw new TypeError(`子菜单代码参数未发布：${name}`);
  return {resource_id: source.resource_id, entity_handle: source.entity_handle, field: source.field};
}

export async function fieldSubmenuCodeValues(names, readField) {
  const {db} = await import('./project-db.js');
  const read = readField ?? ((source) => db.getField(source.resource_id, source.entity_handle, source.field));
  const entries = await Promise.all(names.map(async name => {
    const source = fieldSubmenuCodeSource(name);
    const field = await read(source);
    return [`${source.entity_handle}.${source.field}`, field.value];
  }));
  return Object.fromEntries(entries);
}

export function fieldSubmenuCodeValue(values, name) {
  const source = fieldSubmenuCodeSource(name);
  const path = parametersByName.get(name).valuePath || [];
  const value = path.reduce((value, key) => value?.[key], values[`${source.entity_handle}.${source.field}`]);
  if (!Number.isInteger(value) || value < 0 || value > 255)
    throw new TypeError(`子菜单缺少代码参数：${name}`);
  return value;
}
