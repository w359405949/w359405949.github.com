export function storyCommandPresentation(semantic) {
  const definition = OPERATIONS.get(semantic?.operation);
  if (!definition) return {label: '未确认', group: '其他', description: '未确认', operands: [], confirmed: false};
  const [name, group, description, operands] = definition;
  const directions = {up: '上', down: '下', left: '左', right: '右'};
  const detail = semantic.direction ? directions[semantic.direction]
    : semantic.operation === 'drive-scripted-input' ? ['', '右', '左', '上', '下'][semantic.input_value]
      : semantic.operation === 'wait' ? `${semantic.frames} 帧` : '';
  return {label: `${name}${detail ? ` · ${detail}` : ''}`, group: STORY_COMMAND_GROUPS[group],
    description, operands: semantic.region_operand_index !== undefined ? ['文字区', '文字'] : operands, confirmed: true};
}

export function storyCommandCatalog(declarations, semantics) {
  return declarations.map(declaration => ({...storyCommandPresentation(semantics.get(declaration.opcode)),
    opcode: declaration.opcode, code: declaration.opcode.toString(16).toUpperCase().padStart(2, '0')}));
}
